#!/usr/bin/env bash
# Roll back to the previous immutable Greenfield release (ingress, pi-agent, admin).

set -euo pipefail
umask 077

if [[ "$EUID" -ne 0 ]]; then
  echo "Greenfield production rollback must run as root for credential ownership" >&2
  exit 1
fi

CODE_DIR="${ZD_AGENT_CODE_DIR:-/opt/zd-agent/code}"
STATE_DIR="${CASEWORK_STATE_DIR:-/opt/zd-agent/greenfield}"
RUNTIME_ENV="$STATE_DIR/runtime.env"
DEPLOY_DIR="$CODE_DIR/deploy"
if [[ ! -d "$DEPLOY_DIR" && -d "$CODE_DIR/greenfield/deploy" ]]; then
  DEPLOY_DIR="$CODE_DIR/greenfield/deploy"
fi
COMPOSE_FILE="$DEPLOY_DIR/compose.release.yaml"
LOCK_FILE="${ZD_AGENT_DEPLOY_LOCK_FILE:-/run/lock/zd-agent-deploy.lock}"
NGINX_CONFIG="${CASEWORK_NGINX_CONFIG:-/etc/nginx/sites-enabled/zd-agent.conf}"
RELEASE_ENV="$STATE_DIR/release.env"
PREVIOUS_RELEASE_ENV="$STATE_DIR/previous-release.env"
FAILED_RELEASE_ENV="$STATE_DIR/failed-release.env"

exec 9>"$LOCK_FILE"
flock -w 120 9
test -f "$RUNTIME_ENV"
if [[ ! -f "$PREVIOUS_RELEASE_ENV" ]]; then
  echo "No previous Greenfield release is available for rollback" >&2
  exit 1
fi

unset CASEWORK_RELEASE_QUEUE_LAYOUT CASEWORK_RELEASE_REVISION
unset CASEWORK_INGRESS_IMAGE CASEWORK_ADMIN_IMAGE CASEWORK_PI_AGENT_IMAGE
set -a
# This file is generated by deploy-production.sh with validated image refs.
# shellcheck disable=SC1090
source "$PREVIOUS_RELEASE_ENV"
set +a

case "${CASEWORK_RELEASE_QUEUE_LAYOUT:-legacy}" in
  legacy) legacy_queue=true ;;
  operator_mentions) legacy_queue=false ;;
  *) echo 'Previous release queue layout is unrecognized.' >&2; exit 1 ;;
esac

if [[ ! "${CASEWORK_RELEASE_REVISION:-}" =~ ^[0-9a-f]{40}$ ]]; then
  echo "Previous release revision is invalid" >&2
  exit 1
fi
for image_name in CASEWORK_INGRESS_IMAGE CASEWORK_PI_AGENT_IMAGE CASEWORK_ADMIN_IMAGE; do
  if [[ ! "${!image_name:-}" =~ ^[[:alnum:]][[:alnum:].:/_-]*@sha256:[0-9a-f]{64}$ ]]; then
    echo "Previous ${image_name} is not digest-pinned" >&2
    exit 1
  fi
  docker image inspect "${!image_name}" >/dev/null
done

# shellcheck source=deploy/production-quiesce.sh
source "$DEPLOY_DIR/production-quiesce.sh"
nginx_backup_dir=""
cleanup() {
  local status=$?
  if (( status != 0 )); then
    if [[ -n "$nginx_backup_dir" && -f "$nginx_backup_dir/zd-agent.conf" ]]; then
      cp -- "$nginx_backup_dir/zd-agent.conf" "$NGINX_CONFIG" && nginx -t && systemctl reload nginx || {
        echo "Could not restore Nginx from $nginx_backup_dir/zd-agent.conf" >&2
        nginx_backup_dir=""
      }
    fi
    recover_production
  fi
  if [[ -n "$nginx_backup_dir" ]]; then
    rm -f "$nginx_backup_dir/zd-agent.conf"
    rmdir "$nginx_backup_dir"
  fi
}
trap cleanup EXIT
trap 'exit 129' HUP
trap 'exit 130' INT
trap 'exit 143' TERM

# Both Python services require the exact Alembic head baked into their image.
# Check the pinned images before interrupting the currently serving release.
find_production_db
if [[ -z "$postgres_id" ]]; then
  echo 'Rollback requires the existing Greenfield database.' >&2
  exit 1
fi
applied_head="$(production_db -c 'SELECT version_num FROM public.alembic_version')"
for image in "$CASEWORK_INGRESS_IMAGE" "$CASEWORK_ADMIN_IMAGE"; do
  target_head="$(timeout 20 docker run --rm --network none --entrypoint /app/.venv/bin/python "$image" \
    -c 'from casework_persistence.db import SCHEMA_HEAD; print(SCHEMA_HEAD)')"
  if [[ -z "$applied_head" || "$target_head" != "$applied_head" ]]; then
    echo "Rollback blocked: target image requires $target_head, database is at $applied_head. Use a schema-compatible bundle." >&2
    exit 1
  fi
done

quiesce_production
if [[ "$claim_fenced" != 1 ]]; then
  echo 'Rollback requires an initialized and fenced Greenfield queue.' >&2
  exit 1
fi
production_db -v "legacy_queue=$legacy_queue" < "$DEPLOY_DIR/production-rollback-check.sql"

release_change_started=1
production_db -v "legacy_queue=$legacy_queue" < "$DEPLOY_DIR/production-queue-layout.sql"
python3 "$DEPLOY_DIR/prepare_runtime.py" \
  --state-dir "$STATE_DIR" \
  --revision "$CASEWORK_RELEASE_REVISION" \
  --images-only
configure_production_compose
# Keep the applied schema and skip all Compose migration dependencies.
"${compose[@]}" up -d --no-deps "${services[@]}"
wait_ready ingress http://127.0.0.1:18101/readyz
wait_ready admin http://127.0.0.1:18104/readyz

python3 "$DEPLOY_DIR/configure_runtime.py" \
  --base-url http://127.0.0.1:18104 \
  --internal-token-file "$STATE_DIR/admin-auth/internal-token" \
  --tool-names "$STATE_DIR/tool-names.json"

"${compose[@]}" up -d --no-deps pi-agent
wait_ready pi-agent http://127.0.0.1:18102/readyz
nginx_backup_dir="$(mktemp -d "$STATE_DIR/.rollback-nginx.XXXXXX")"
python3 "$DEPLOY_DIR/nginx_switch.py" \
  --config "$NGINX_CONFIG" --backup "$nginx_backup_dir/zd-agent.conf"
nginx -t
systemctl reload nginx
curl -fsS --max-time 5 https://zendesk.smlershou.top/healthz >/dev/null

release_claim_fence
if [[ -f "$RELEASE_ENV" ]]; then
  install -m 600 "$RELEASE_ENV" "$FAILED_RELEASE_ENV.tmp"
  mv -f "$FAILED_RELEASE_ENV.tmp" "$FAILED_RELEASE_ENV"
fi
install -m 600 "$PREVIOUS_RELEASE_ENV" "$RELEASE_ENV.tmp"
mv -f "$RELEASE_ENV.tmp" "$RELEASE_ENV"
if [[ -f "$FAILED_RELEASE_ENV" ]]; then
  install -m 600 "$FAILED_RELEASE_ENV" "$PREVIOUS_RELEASE_ENV.tmp"
  mv -f "$PREVIOUS_RELEASE_ENV.tmp" "$PREVIOUS_RELEASE_ENV"
fi
echo "Production rolled back to Greenfield revision ${CASEWORK_RELEASE_REVISION}."
