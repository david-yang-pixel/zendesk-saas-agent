#!/usr/bin/env bash
# Roll back to the previous immutable Greenfield release (ingress, pi-agent, admin).

set -euo pipefail
umask 077

if [[ "$EUID" -ne 0 ]]; then
  echo "Greenfield production rollback must run as root for credential ownership" >&2
  exit 1
fi

CODE_DIR="${ZD_AGENT_CODE_DIR:-/opt/zd-agent/code}"
STATE_DIR="${CASEWORK_STATE_DIR:-/opt/zd-agent/greenfield}"
SOURCE_ENV="${ZD_AGENT_SOURCE_ENV:-/opt/zd-agent/.env}"
RUNTIME_ENV="$STATE_DIR/runtime.env"
DEPLOY_DIR="$CODE_DIR/deploy"
if [[ ! -d "$DEPLOY_DIR" && -d "$CODE_DIR/greenfield/deploy" ]]; then
  DEPLOY_DIR="$CODE_DIR/greenfield/deploy"
fi
COMPOSE_FILE="$DEPLOY_DIR/compose.release.yaml"
LOCK_FILE="${ZD_AGENT_DEPLOY_LOCK_FILE:-/run/lock/zd-agent-deploy.lock}"
NGINX_CONFIG="${CASEWORK_NGINX_CONFIG:-/etc/nginx/sites-enabled/zd-agent.conf}"
RELEASE_ENV="$STATE_DIR/release.env"
PREVIOUS_RELEASE_ENV="$STATE_DIR/previous-release.env"
FAILED_RELEASE_ENV="$STATE_DIR/failed-release.env"
SERVICES=(ingress pi-agent admin)

exec 9>"$LOCK_FILE"
flock -w 120 9
test -f "$RUNTIME_ENV"
if [[ ! -f "$PREVIOUS_RELEASE_ENV" ]]; then
  echo "No previous Greenfield release is available for rollback" >&2
  exit 1
fi

set -a
# This file is generated by deploy-production.sh with validated image refs.
# shellcheck disable=SC1090
source "$PREVIOUS_RELEASE_ENV"
set +a

if [[ ! "${CASEWORK_RELEASE_REVISION:-}" =~ ^[0-9a-f]{40}$ ]]; then
  echo "Previous release revision is invalid" >&2
  exit 1
fi
for image_name in CASEWORK_INGRESS_IMAGE CASEWORK_PI_AGENT_IMAGE CASEWORK_ADMIN_IMAGE; do
  if [[ ! "${!image_name:-}" =~ @sha256:[0-9a-f]{64}$ ]]; then
    echo "Previous ${image_name} is not digest-pinned" >&2
    exit 1
  fi
  docker image inspect "${!image_name}" >/dev/null
done

compose=(docker compose --project-name casework-greenfield --env-file "$RUNTIME_ENV" -f "$COMPOSE_FILE")
"${compose[@]}" stop "${SERVICES[@]}"

# prepare_runtime.py writes these image references into runtime.env, so every
# later Compose command keeps using the rolled-back digests.
export CASEWORK_INGRESS_IMAGE CASEWORK_PI_AGENT_IMAGE CASEWORK_ADMIN_IMAGE
export CASEWORK_RELEASE_REVISION
python3 "$DEPLOY_DIR/prepare_runtime.py" \
  --source-env "$SOURCE_ENV" \
  --state-dir "$STATE_DIR" \
  --revision "$CASEWORK_RELEASE_REVISION"
"${compose[@]}" up -d postgres
# Keep the current schema. Greenfield rollbacks never run an automatic
# destructive database downgrade.
"${compose[@]}" up -d --no-deps "${SERVICES[@]}"

for url in \
  http://127.0.0.1:18101/readyz \
  http://127.0.0.1:18102/readyz \
  http://127.0.0.1:18104/readyz; do
  ready=0
  for _ in $(seq 1 60); do
    if curl -fsS --max-time 3 "$url" >/dev/null; then
      ready=1
      break
    fi
    sleep 3
  done
  if [[ "$ready" != "1" ]]; then
    echo "${url} did not become ready" >&2
    exit 1
  fi
done

# Preserve the Agent's running/paused state, exactly as a deployment does.
python3 "$DEPLOY_DIR/configure_runtime.py" \
  --base-url http://127.0.0.1:18104 \
  --internal-token-file "$STATE_DIR/admin-auth/internal-token" \
  --tool-names "$STATE_DIR/tool-names.json"

python3 "$DEPLOY_DIR/nginx_switch.py" \
  --config "$NGINX_CONFIG" --backup "$STATE_DIR/nginx.rollback.tmp"
nginx -t
systemctl reload nginx
curl -fsS --max-time 5 https://zendesk.smlershou.top/healthz >/dev/null

if [[ -f "$RELEASE_ENV" ]]; then
  cp "$RELEASE_ENV" "$FAILED_RELEASE_ENV"
  chmod 600 "$FAILED_RELEASE_ENV"
fi
cp "$PREVIOUS_RELEASE_ENV" "$RELEASE_ENV"
chmod 600 "$RELEASE_ENV"
if [[ -f "$FAILED_RELEASE_ENV" ]]; then
  cp "$FAILED_RELEASE_ENV" "$PREVIOUS_RELEASE_ENV"
  chmod 600 "$PREVIOUS_RELEASE_ENV"
fi
rm -f "$STATE_DIR/nginx.rollback.tmp"
echo "Production rolled back to Greenfield revision ${CASEWORK_RELEASE_REVISION}."
