"""ZendeskPublicReply tool: send a customer-visible public comment on a SaaS ticket.

Why a separate tool from :class:`zendesk.ZendeskInternalReply`
------------------------------------------------------------
Internal Note 与 Public Reply 是两类**完全不同**的对外动作：

- **Internal Note** 给 Support Engineer 看，agent 写"草稿 + 分析 + 引导"三段式
  HTML 卡片，可以随便写、SE 审完发不发是 SE 的事；**风险低**。
- **Public Reply** 客户**直接看到 + 邮件通知发出去**，agent 说错话不能撤回（Zendesk
  能编辑但客户邮件已经投递了），**风险高**。

为防止 agent 把两个语境混淆（用 internal 风格写 public reply 给客户读到内部摘要
卡片是灾难），把 public reply 做成**完全独立的工具**，参数 schema、措辞约束、
footer 处理都不一样。

设计决策（来自跟用户的 2026-05-13 设计讨论）
---------------------------------------------
1. **永远附 footer**：硬编码追加，LLM 不能跳过；明示 AI 身份 + 给客户"回复 human"
   逃生口。
2. **统一英文**：所有 SaaS messaging 工单的公开回复一律 English，不跟随客户语言。
   原因：模板一致性 + 国际化默认 + LLM 英文质量最稳。
3. **reply_type 区分场景**：ask / solution / handoff / closed 四种，footer 措辞一致
   （为简化），但 handoff / closed 不重复提"reply with human"避免冗余。
4. **不做 HTML 渲染**：public reply 是给客户读的，纯文本 / Markdown 已经够，不要
   学 Internal Note 那样塞复杂 HTML 卡片。
5. **kill switch**：``cfg.public_reply.enabled = false`` 时工具直接 return 失败，
   出问题一秒下线无需 redeploy。
"""
from __future__ import annotations

from typing import Any, TYPE_CHECKING

from zd.client import ZendeskError

from zd_agent.config import get_config
from zd_agent.log import get_logger
from zd_agent.tools.base import Tool, ToolResult
from zd_agent.tools.zendesk import (
    _call_with_rate_limit_retry,
    _format_error,
    _get_client,
)

if TYPE_CHECKING:
    from zd_agent.session.agent_session import AgentSession

logger = get_logger(module="tools.zendesk_public_reply")


# ---------------------------------------------------------------------------
# Footer：硬编码常量。所有 public reply 末尾强制追加，LLM 无法跳过 / 改措辞。
#
# 2026-05-25 重写：之前 "If this doesn't resolve your issue or you'd prefer
# human assistance, please reply with 'human'" 给客户太强的"agent 搞不定，
# 找人吧"心理暗示，观察到 #2634 客户上来一句"你好"看到 footer 立刻喊人工。
#
# 新措辞策略：
# 1. 先正向邀请客户提供问题（"share your question and I'll dig in"）→
#    心理上客户先看到 agent 主动接活，对 agent 有信心
# 2. "doesn't resolve" 条件仍保留 escape hatch（合规要求 + trigger_decider
#    fast-path 依赖 'human' 关键词检测）
# 3. "support engineer will take it from here" 替代 "connect you with a
#    teammate" → 强调"专业工程师"而非"队友"，提升后续 wait 期间的客户耐心
# 4. "Dify SaaS Agent" 明示身份仍保留（合规 + 反欺诈底线）
# ---------------------------------------------------------------------------
_FOOTER_STANDARD = (
    "\n\n---\n"
    "🤖 Dify SaaS Agent here — share your question and I'll dig in to find an answer.\n"
    'If that doesn\'t resolve it, reply with "human" and a support engineer will take it from here.'
)

# handoff 类回复：客户已经被转给真人了，再说"reply with human"显得弱智
_FOOTER_HANDOFF = (
    "\n\n---\n"
    "🤖 This reply was generated by Dify SaaS Agent."
)

# closed 类回复：客户主动说"解决了"，温和收尾，给重启入口但不催回复
_FOOTER_CLOSED = (
    "\n\n---\n"
    "🤖 This reply was generated by Dify SaaS Agent. "
    "If you run into the issue again, feel free to reply here or open a new ticket."
)

# reply_type → footer 映射
_FOOTER_BY_TYPE = {
    "ask": _FOOTER_STANDARD,      # 模板 A/B/C/D：agent 在向客户问问题
    "solution": _FOOTER_STANDARD, # 模板 F：agent 给出解决方案
    "handoff": _FOOTER_HANDOFF,   # 模板 E：已转人工
    "closed": _FOOTER_CLOSED,     # 模板 G：客户说解决了
}

_VALID_REPLY_TYPES = frozenset(_FOOTER_BY_TYPE)


# docs.dify.ai 的源码 markdown 文件路径会带 .md 后缀（给 LLM 用的 llms.txt
# 索引列出的就是 .md 形式），但客户点开看到的是 raw markdown 源文本（content-type:
# text/markdown），非常丑。HTML 形式（无 .md）才是给人看的正常文档页。
# Regex：替换 docs.dify.ai/<path>.md → docs.dify.ai/<path>（保留 path）
import re as _re
_DOCS_MD_PATTERN = _re.compile(
    r"(https?://docs\.dify\.ai/[^\s\)\]>]+?)\.md\b"
)


def _strip_docs_md_suffix(body: str) -> str:
    """把 body 里所有 docs.dify.ai/...md 形式去掉 .md 后缀。

    只针对 docs.dify.ai 域名，避免误伤其它合法 .md URL（如 GitHub）。
    """
    return _DOCS_MD_PATTERN.sub(r"\1", body)


def _append_footer(body: str, reply_type: str) -> str:
    """按 reply_type 在 body 末尾追加 footer。

    幂等：如果 body 已经以对应 footer 结尾（说明 LLM 试图自己加），不重复。
    顺手清理：docs.dify.ai 的 .md 后缀（agent 易从 llms.txt 抓到 .md 形式
    给客户但 .md 服务的是 raw markdown 不是渲染好的文档）。
    """
    body = _strip_docs_md_suffix(body)
    footer = _FOOTER_BY_TYPE[reply_type]
    if body.rstrip().endswith(footer.rstrip()):
        return body
    return body.rstrip() + footer


async def send_public_reply(
    *,
    ticket_id: int,
    body: str,
    reply_type: str,
    dry_run: bool = False,
) -> tuple[bool, str]:
    """直接发 public reply 的公共入口（不需要 AgentSession）。

    给 trigger_consumer / 集成测试 / CLI 用。和 ZendeskPublicReply Tool 共享
    底层送达逻辑（footer 追加 + kill switch + reply_ticket(public=True)），但
    **不跑 pre_send_check**（pre_send_check 主要给 agent 长时间分析后用，
    trigger 层 evaluate→send 间隔毫秒级，没必要）。

    Returns:
        (success, message_or_error)
    """
    # Kill switch
    cfg = get_config()
    if not getattr(cfg, "public_reply", None) or not cfg.public_reply.enabled:
        logger.warning(
            "public_reply_disabled_direct",
            ticket_id=ticket_id,
            reason="cfg.public_reply.enabled=false",
        )
        return (
            False,
            "Public reply is currently disabled (kill switch).",
        )

    # 参数校验
    body = (body or "").strip()
    if not body:
        return False, "body is empty"
    if reply_type not in _VALID_REPLY_TYPES:
        return False, f"invalid reply_type: {reply_type!r}"

    # Footer 追加
    body_with_footer = _append_footer(body, reply_type)

    if dry_run:
        logger.info(
            "public_reply_dry_run_direct",
            ticket_id=ticket_id, reply_type=reply_type,
            body_len=len(body_with_footer),
        )
        return True, "[Dry Run] Not sent."

    logger.info(
        "public_reply_send_start_direct",
        ticket_id=ticket_id, reply_type=reply_type,
        body_len=len(body_with_footer),
    )
    try:
        client = _get_client()
        await _call_with_rate_limit_retry(
            client.reply_ticket,
            ticket_id,
            body_with_footer,
            True,  # public=True
        )
        logger.info(
            "public_reply_sent_direct",
            ticket_id=ticket_id, reply_type=reply_type,
        )
        # M8 metric: 成功发出一条公共回复
        try:
            from zd_agent.observability.metrics import (
                emit_agent_public_reply_sent,
            )
            emit_agent_public_reply_sent(
                ticket_id=ticket_id,
                reply_type=reply_type,
                body_chars=len(body),  # 不含 footer
            )
        except Exception:
            pass  # metric 失败不影响主流程
        return True, f"已发送 Public Reply 到工单 #{ticket_id}"
    except ZendeskError as e:
        logger.warning(
            "public_reply_direct_zendesk_error",
            ticket_id=ticket_id, error=str(e)[:200],
        )
        return False, _format_error(e)
    except Exception as e:
        logger.error(
            "public_reply_direct_send_failed",
            ticket_id=ticket_id, error=str(e)[:200],
            exc_info=True,
        )
        return False, f"{type(e).__name__}: {e}"


class ZendeskPublicReply(Tool):
    """发送公开回复（客户可见）。**只用于 SaaS messaging 工单**。

    与 ``zendesk_internal_reply`` 互斥：

    - Internal Reply 给同事看，不会触发客户邮件
    - Public Reply 给**客户**看 + Zendesk 会发邮件通知客户 / 在 messaging widget 显示

    工具自动追加 footer（明示 AI 身份 + 提供"回复 human" 逃生口）。LLM
    在 ``body`` 里**不需要**也**不应该**自己写 footer，写了会被检测到不重复加。
    """

    name = "zendesk_public_reply"
    description = (
        "向 SaaS messaging 工单发送 Public Reply（客户可见的公开评论）。"
        "正文应该用 English（统一语言）。系统会自动追加 footer 注明 AI 身份并提示"
        "客户可回复 'human' 转人工，**不要在 body 里自己写 footer**。"
        "reply_type 决定 footer 措辞变体："
        "ask（向客户问问题，模板 A/B/C/D）/ "
        "solution（给出解决方案，模板 F）/ "
        "handoff（已转人工，模板 E）/ "
        "closed（工单收尾，模板 G）。"
    )
    parameters = {
        "type": "object",
        "properties": {
            "ticket_id": {
                "type": "integer",
                "description": "工单 ID",
            },
            "body": {
                "type": "string",
                "description": (
                    "公开回复正文，**English only**，Markdown 格式。"
                    "不要包含 footer——系统会自动追加。"
                ),
            },
            "reply_type": {
                "type": "string",
                "enum": sorted(_VALID_REPLY_TYPES),
                "description": (
                    "决定 footer 措辞变体："
                    "ask（向客户索取更多信息）/ "
                    "solution（agent 给出解决方案）/ "
                    "handoff（已转人工）/ "
                    "closed（客户已解决，收尾）"
                ),
            },
        },
        "required": ["ticket_id", "body", "reply_type"],
    }
    group = "zendesk"
    concurrency_safe = False
    is_write_operation = True

    async def execute(
        self, args: dict[str, Any], session: "AgentSession",
    ) -> ToolResult:
        ticket_id = args.get("ticket_id")
        body = (args.get("body") or "").strip()
        reply_type = args.get("reply_type")

        # 1. Kill switch（出问题一秒下线）
        cfg = get_config()
        if not getattr(cfg, "public_reply", None) or not cfg.public_reply.enabled:
            logger.warning(
                "public_reply_disabled",
                ticket_id=ticket_id,
                reason="cfg.public_reply.enabled=false",
            )
            return ToolResult(
                success=False,
                error=(
                    "Public reply is currently disabled (kill switch). "
                    "Fall back to zendesk_internal_reply."
                ),
            )

        # 2. 参数校验
        if not isinstance(ticket_id, int) or ticket_id <= 0:
            return ToolResult(
                success=False,
                error=f"invalid ticket_id: {ticket_id!r}",
            )
        if not body:
            return ToolResult(success=False, error="body is empty")
        if reply_type not in _VALID_REPLY_TYPES:
            return ToolResult(
                success=False,
                error=(
                    f"invalid reply_type: {reply_type!r}; "
                    f"must be one of {sorted(_VALID_REPLY_TYPES)}"
                ),
            )

        # 3. Footer 强制追加（幂等）
        body_with_footer = _append_footer(body, reply_type)

        # 4. dry_run 模式：只存草稿不发
        session.reply_draft = body_with_footer
        if session.dry_run:
            logger.info(
                "public_reply_dry_run",
                ticket_id=ticket_id, reply_type=reply_type,
                body_len=len(body_with_footer),
            )
            return ToolResult(
                output=(
                    f"[Dry Run] Public reply 已存草稿（未发送）。\n\n"
                    f"--- 草稿内容 ---\n{body_with_footer}"
                ),
            )

        # 4b. Pre-send freshness check（M5）
        # 只在 session 有 snapshot 时跑（snapshot=0 表示未设置 / legacy 路径，跳过）
        # handoff / closed 类回复跳过 freshness check：
        #   - handoff 是"已转人工"通知，发就发，不需等更多客户消息
        #   - closed 是客户已说解决，发就发
        if (
            reply_type in ("ask", "solution")
            and session.customer_msgs_snapshot_count > 0
        ):
            from zd_agent.config import EnvSettings
            from zd_agent.runtime.pre_send_check import pre_send_check_or_abort
            from zd_agent.entry.saas_app import _fetch_customer_messages

            async def _fetch():
                msgs, _ticket = await _fetch_customer_messages(ticket_id)
                return msgs or []

            env = EnvSettings()
            try:
                check = await pre_send_check_or_abort(
                    ticket_id=ticket_id,
                    snapshot_count=session.customer_msgs_snapshot_count,
                    snapshot_last_id=session.customer_msgs_snapshot_last_id or None,
                    fetch_messages_fn=_fetch,
                    model=cfg.trigger_decider.llm_model,
                    api_key=env.openai_api_key,
                )
            except Exception as e:
                logger.warning(
                    "public_reply_pre_send_check_error",
                    ticket_id=ticket_id, error=str(e)[:200],
                )
                # check 失败保守放行（避免阻塞所有回复）
                check = None

            if check is not None and not check.continue_send:
                logger.info(
                    "public_reply_aborted_pre_send_check",
                    ticket_id=ticket_id, reply_type=reply_type,
                    reason=check.reason,
                    new_msg_count=check.new_messages_count,
                )
                return ToolResult(
                    success=False,
                    error=(
                        f"Pre-send check abort: customer added "
                        f"{check.new_messages_count} new substantive message(s) "
                        f"({check.reason}). Re-analyze with fresh context."
                    ),
                )

        # 5. 真发送：调 client.reply_ticket(..., public=True)
        logger.info(
            "public_reply_send_start",
            ticket_id=ticket_id, reply_type=reply_type,
            body_len=len(body_with_footer),
        )
        try:
            client = _get_client()
            await _call_with_rate_limit_retry(
                client.reply_ticket,
                ticket_id,
                body_with_footer,
                True,  # public=True ← 关键区别
            )
            session.reply_sent = True
            logger.info(
                "public_reply_sent",
                ticket_id=ticket_id, reply_type=reply_type,
            )
            # M8 metric: agent 通过 Tool 路径成功发出公共回复
            try:
                from zd_agent.observability.metrics import (
                    emit_agent_public_reply_sent,
                )
                emit_agent_public_reply_sent(
                    ticket_id=ticket_id,
                    reply_type=reply_type,
                    body_chars=len(body),  # 不含 footer
                )
            except Exception:
                pass  # metric 失败不影响主流程
            return ToolResult(
                output=(
                    f"已发送 Public Reply 到工单 #{ticket_id}（reply_type={reply_type}）"
                ),
            )
        except ZendeskError as e:
            logger.warning(
                "public_reply_zendesk_error",
                ticket_id=ticket_id, error=str(e)[:200],
            )
            return ToolResult(success=False, error=_format_error(e))
        except Exception as e:
            logger.error(
                "public_reply_send_failed",
                ticket_id=ticket_id, error=str(e)[:200],
                exc_info=True,
            )
            return ToolResult(
                success=False, error=f"{type(e).__name__}: {e}",
            )
