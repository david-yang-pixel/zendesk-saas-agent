"""Best-effort Feishu notification helpers for session lifecycle events."""

from __future__ import annotations

from pathlib import Path
import re
from typing import Any

from zd_agent.integrations.notification_service import push_notification_card
from zd_agent.log import get_logger
from zd_agent.services.notification_outbox import (
    NotificationOutbox,
    reconcile_notifications,
)
from zd_agent.session.agent_session import SessionStatus

logger = get_logger(module="services.feishu_notifications")

_FOOTER_MARKERS = (
    "This reply was sent by Dify AI Agent.",
    "This reply was sent by Dify AI Support.",
    "🤖 This message is sent by Dify AI",
    "🤖 This reply was generated by Dify SaaS Agent",
)
_GREETING_RE = re.compile(
    r"^(hi|hello|hey)(?:\s+[\w-]{1,40})?[,.!。！？]\s+",
    re.IGNORECASE,
)
_SENTENCE_SPLIT_RE = re.compile(r"(?<=[.!?。！？])\s+")
_REPLY_DIGEST_MAX_CHARS = 320
_MAX_AUTOMATION_ATTEMPTS = 3


def _has_successful_ticket_done(session: Any) -> bool:
    """Recognize a completion card recorded by a pre-v2 archived session."""
    for item in getattr(session, "tool_call_log", []) or []:
        if item.get("tool") != "feishu_push":
            continue
        args = item.get("args") or {}
        if args.get("card_type") == "ticket_done" and item.get("success"):
            return True
    return False


def _strip_public_reply_footer(text: str) -> str:
    stripped = text
    for marker in _FOOTER_MARKERS:
        index = stripped.find(marker)
        if index != -1:
            stripped = stripped[:index]
    return stripped.strip()


def _truncate_digest(text: str) -> str:
    cleaned = text.strip()
    if len(cleaned) <= _REPLY_DIGEST_MAX_CHARS:
        return cleaned
    return cleaned[: _REPLY_DIGEST_MAX_CHARS - 3].rstrip() + "..."


def _reply_digest(reply_draft: str, *, max_sentences: int = 2) -> str:
    without_footer = _strip_public_reply_footer(reply_draft)
    lines = [
        line.strip().strip("\u200b")
        for line in without_footer.splitlines()
        if line.strip().strip("\u200b")
    ]
    compact = " ".join(lines).strip()
    compact = _GREETING_RE.sub("", compact).strip()
    if not compact:
        return "已发送客户回复，正文见 Zendesk。"

    sentences = [
        sentence.strip()
        for sentence in _SENTENCE_SPLIT_RE.split(compact)
        if sentence.strip()
    ]
    return _truncate_digest(" ".join((sentences or [compact])[:max_sentences]))


def _ticket_done_summary(session: Any) -> str:
    reply_draft = (getattr(session, "reply_draft", "") or "").strip()
    if reply_draft:
        summary = (f"处理结果：已回复客户\n客户回复：{_reply_digest(reply_draft)}")[
            :1800
        ]
        return summary
    summary = (
        "处理结果：已完成\n"
        f"关键事实：Agent completed ticket #{getattr(session, 'ticket_id', '')}."
    )
    return summary


async def notify_ticket_done_best_effort(session: Any) -> bool:
    """Push a deterministic ticket_done card after successful public reply.

    v2 owns this notification outside the model tool registry. The tool-log
    check only prevents a duplicate when resuming a frozen pre-v2 session.
    """
    ticket_id = getattr(session, "ticket_id", None)
    if _has_successful_ticket_done(session):
        logger.info("feishu_ticket_done_skip_already_sent", ticket_id=ticket_id)
        return False

    payload = await push_notification_card(
        card_type="ticket_done",
        ticket_id=str(ticket_id),
        content=_ticket_done_summary(session),
        zendesk_url=f"https://langgenius.zendesk.com/agent/tickets/{ticket_id}",
    )
    if not payload.get("success"):
        logger.warning(
            "feishu_ticket_done_failed",
            ticket_id=ticket_id,
            error=str(payload.get("error") or "unknown error"),
            code=payload.get("code"),
        )
        return False

    logger.info("feishu_ticket_done_pushed", ticket_id=ticket_id)
    return True


def _outcome_kind(session: Any) -> str:
    delivery_state = str(getattr(session, "casework_delivery_state", "") or "")
    status = getattr(session, "status", None)
    if (
        status is SessionStatus.COMPLETED
        and bool(getattr(session, "reply_sent", False))
        and delivery_state not in {"failed", "ambiguous"}
    ):
        return "success"
    if status in {SessionStatus.FAILED, SessionStatus.TIMEOUT} or delivery_state in {
        "failed",
        "ambiguous",
    }:
        attempt = int(getattr(session, "casework_attempt", 1) or 1)
        return "failed" if attempt >= _MAX_AUTOMATION_ATTEMPTS else ""
    return ""


def _outcome_content(session: Any, outcome: str) -> str:
    if outcome == "success":
        reply = str(getattr(session, "reply_draft", "") or "").strip()
        return "处理结果：已成功回复客户\n\n实际发送正文：\n" + (
            reply or "（正文未记录，请在 Zendesk 查看。）"
        )
    return "\n".join(
        (
            "处理结果：自动回复未确认成功，需要人工检查",
            f"会话状态：{getattr(getattr(session, 'status', None), 'value', '')}",
            "发送阶段："
            f"{str(getattr(session, 'casework_delivery_state', '') or 'analysis')}",
            "错误摘要："
            f"{str(getattr(session, 'error_message', '') or 'unknown error')[:1000]}",
        )
    )


async def notify_session_outcome_durable(session: Any, cfg: Any) -> bool:
    """Persist and immediately attempt a success/failure lifecycle card."""
    outcome = _outcome_kind(session)
    ownership_action = str(
        getattr(session, "casework_ownership_action", "") or "none"
    )
    if not outcome or (outcome == "success" and ownership_action not in {"", "none"}):
        return False
    ticket_id = int(getattr(session, "ticket_id", 0) or 0)
    attempt_id = str(
        getattr(session, "delivery_attempt_id", "")
        or getattr(session, "session_id", "")
    )
    reference = f"session-outcome:{ticket_id}:{attempt_id}:{outcome}"
    state_dir = Path(cfg.resources.base_dir) / cfg.resources.state_dir
    store = NotificationOutbox(state_dir / "notification_outbox.sqlite3")
    store.prepare(
        reference=reference,
        ticket_id=ticket_id,
        card_type="ticket_done" if outcome == "success" else "ticket_escalate",
        title="自动回复发送成功" if outcome == "success" else "自动回复发送失败",
        content=_outcome_content(session, outcome),
        zendesk_url=f"https://langgenius.zendesk.com/agent/tickets/{ticket_id}",
        urgent=outcome == "failed",
    )
    before = len(store.pending(limit=100))
    await reconcile_notifications(store=store, push=push_notification_card, limit=20)
    after = len(store.pending(limit=100))
    return after < before
