"""Tests for human takeover detection (Case 3 gap: SE 中途插队).

3 个 takeover 检测路径 + 不该误判的情况：
1. assignee 是非 agent 的真人 SE → detected
2. 最后 public comment author 是别的 SE (非 agent 非客户) → detected
3. author=agent_uid 但 body 不含 'Dify SaaS Agent' footer → yonggang 手动发 → detected
4. ✅ 不该误判：author=agent_uid 且 body 含 footer → 是 agent 自己发的 → NOT detected
5. assignee=agent_uid 也视为已有真实受托人 → detected
6. ✅ 不该误判：AI Agent / SaaS 自动身份 → NOT detected
7. ✅ 不该误判：没受托人且没 public comment → NOT detected
8. ✅ fetch 失败且没受托人时保守放过 → NOT detected
"""
from __future__ import annotations

from unittest.mock import patch

import pytest

from zd_agent.config import AppConfig, ZendeskConfig
from zd_agent.services.human_takeover import detect_human_takeover

AGENT_UID = 45433304089364
AI_AGENT_UID = 46493567999892
OTHER_SE_UID = 99999999
CUSTOMER_UID = 12345678


def _make_mcp_call(comments_resp: dict | None = None, raise_on_fetch: bool = False):
    async def fake_call(name: str, arguments: dict):
        assert name == "get_ticket_comments"
        if raise_on_fetch:
            return {"success": False, "code": "ZENDESK_API_ERROR", "error": "zd 500"}
        return {"success": True, "data": comments_resp or {"comments": []}}

    return fake_call


def _ticket(assignee_id: int | None = None,
            requester_id: int = CUSTOMER_UID) -> dict:
    return {"id": 1234, "assignee_id": assignee_id, "requester_id": requester_id}


# ---------------------------------------------------------------------------
# 检测应触发 = 3 路径
# ---------------------------------------------------------------------------

class TestDetected:
    @pytest.mark.asyncio
    async def test_assignee_is_other_se(self) -> None:
        """assignee 非空 → 视为已有受托人，触发"""
        detected, reason = await detect_human_takeover(
            ticket_id=1234,
            ticket_info=_ticket(assignee_id=OTHER_SE_UID),
            agent_user_id=AGENT_UID,
        )
        assert detected is True
        assert str(OTHER_SE_UID) in reason

    @pytest.mark.asyncio
    async def test_last_public_reply_by_other_se(self) -> None:
        """最后一条 public 是别的 SE 发的 (非 agent 非客户) → 触发"""
        comments = {
            "comments": [
                {"id": 1, "author_id": CUSTOMER_UID, "public": False, "body": "init"},
                {"id": 2, "author_id": OTHER_SE_UID, "public": True, "body": "hi"},
            ]
        }
        with patch(
            "zd_agent.services.human_takeover.call_zendesk_tool",
            side_effect=_make_mcp_call(comments),
        ):
            detected, reason = await detect_human_takeover(
                ticket_id=1234,
                ticket_info=_ticket(),
                agent_user_id=AGENT_UID,
            )
        assert detected is True
        assert "other SE" in reason or str(OTHER_SE_UID) in reason

    @pytest.mark.asyncio
    async def test_yonggang_manual_public_reply(self) -> None:
        """author=agent_uid 但 body 不含 footer → yonggang 通过 UI 手动发的"""
        comments = {
            "comments": [
                {"id": 1, "author_id": CUSTOMER_UID, "public": True, "body": "hi"},
                {
                    "id": 2, "author_id": AGENT_UID, "public": True,
                    "body": "Sure, let me check this for you tomorrow.",  # 无 footer
                },
            ]
        }
        with patch(
            "zd_agent.services.human_takeover.call_zendesk_tool",
            side_effect=_make_mcp_call(comments),
        ):
            detected, reason = await detect_human_takeover(
                ticket_id=1234,
                ticket_info=_ticket(),
                agent_user_id=AGENT_UID,
            )
        assert detected is True
        assert "footer" in reason or "missing" in reason


# ---------------------------------------------------------------------------
# 不该误判
# ---------------------------------------------------------------------------

class TestNotDetected:
    @pytest.mark.asyncio
    async def test_agent_self_sent_public_with_footer(self) -> None:
        """agent 自动发的 public（含 Dify SaaS Agent footer）不该误判"""
        comments = {
            "comments": [
                {"id": 1, "author_id": CUSTOMER_UID, "public": True, "body": "hi"},
                {
                    "id": 2, "author_id": AGENT_UID, "public": True,
                    "body": (
                        "Hi Alice! What can I help you with?\n\n---\n"
                        "🤖 This reply was generated by Dify SaaS Agent. ..."
                    ),
                },
            ]
        }
        with patch(
            "zd_agent.services.human_takeover.call_zendesk_tool",
            side_effect=_make_mcp_call(comments),
        ):
            detected, reason = await detect_human_takeover(
                ticket_id=1234,
                ticket_info=_ticket(),
                agent_user_id=AGENT_UID,
            )
        assert detected is False
        assert reason == ""

    @pytest.mark.asyncio
    async def test_assignee_is_agent_uid_still_takeover(self) -> None:
        """只看是否已有受托人：assignee=agent_uid 也触发让位。"""
        detected, reason = await detect_human_takeover(
            ticket_id=1234,
            ticket_info=_ticket(assignee_id=AGENT_UID),
            agent_user_id=AGENT_UID,
        )
        assert detected is True
        assert str(AGENT_UID) in reason

    @pytest.mark.asyncio
    async def test_ai_agent_assignee_still_takeover(self) -> None:
        """AI Agent / SaaS 自动身份不算人工受托人。"""
        cfg = AppConfig()
        cfg.zendesk = ZendeskConfig(non_human_assignee_ids=[AI_AGENT_UID])
        with patch("zd_agent.services.human_takeover.get_config", return_value=cfg), patch(
            "zd_agent.services.human_takeover.call_zendesk_tool",
            side_effect=_make_mcp_call({"comments": []}),
        ):
            detected, reason = await detect_human_takeover(
                ticket_id=1234,
                ticket_info=_ticket(assignee_id=AI_AGENT_UID),
                agent_user_id=AGENT_UID,
            )
        assert detected is False
        assert reason == ""

    @pytest.mark.asyncio
    async def test_no_public_comment_yet(self) -> None:
        """工单还没 public reply → 不算 takeover"""
        comments = {
            "comments": [
                {"id": 1, "author_id": CUSTOMER_UID, "public": False, "body": "init"},
            ]
        }
        with patch(
            "zd_agent.services.human_takeover.call_zendesk_tool",
            side_effect=_make_mcp_call(comments),
        ):
            detected, _ = await detect_human_takeover(
                ticket_id=1234,
                ticket_info=_ticket(),
                agent_user_id=AGENT_UID,
            )
        assert detected is False

    @pytest.mark.asyncio
    async def test_last_public_by_customer_not_takeover(self) -> None:
        """最后 public 是客户发的（不是 SE）→ 不该误判"""
        comments = {
            "comments": [
                {"id": 1, "author_id": AGENT_UID, "public": True,
                 "body": "Reply\n\n🤖 Dify SaaS Agent"},
                {"id": 2, "author_id": CUSTOMER_UID, "public": True,
                 "body": "thanks!"},
            ]
        }
        with patch(
            "zd_agent.services.human_takeover.call_zendesk_tool",
            side_effect=_make_mcp_call(comments),
        ):
            detected, _ = await detect_human_takeover(
                ticket_id=1234,
                ticket_info=_ticket(),
                agent_user_id=AGENT_UID,
            )
        assert detected is False

    @pytest.mark.asyncio
    async def test_fetch_failure_conservative(self) -> None:
        """fetch comments 抛异常 → 保守放过（不触发误判）"""
        with patch(
            "zd_agent.services.human_takeover.call_zendesk_tool",
            side_effect=_make_mcp_call(raise_on_fetch=True),
        ):
            detected, _ = await detect_human_takeover(
                ticket_id=1234,
                ticket_info=_ticket(),
                agent_user_id=AGENT_UID,
            )
        assert detected is False

    @pytest.mark.asyncio
    async def test_assignee_does_not_need_agent_uid_config(self) -> None:
        """assignee 判断只依赖是否有受托人，不依赖 agent_user_id。"""
        detected, reason = await detect_human_takeover(
            ticket_id=1234,
            ticket_info=_ticket(assignee_id=OTHER_SE_UID),
            agent_user_id=0,
        )
        assert detected is True
        assert str(OTHER_SE_UID) in reason
